"""
Run every query in sql/ against BigQuery, save each result to results/<name>.csv,
and write results/SUMMARY.md with a preview table per question.

Before running each query it does a free "dry run" to see how much data the query
will scan, and skips anything over the limit, so you never burn through the
sandbox's free 1 TB/month by accident.

Usage:
    python scripts/run_analysis.py --project YOUR_GCP_PROJECT_ID
    python scripts/run_analysis.py --project YOUR_GCP_PROJECT_ID --only q02
"""
import argparse
import csv
from pathlib import Path

from google.cloud import bigquery

ROOT = Path(__file__).resolve().parent.parent
SQL_DIR = ROOT / "sql"
RESULTS_DIR = ROOT / "results"
PREVIEW_ROWS = 20


def title_of(sql_text):
    for line in sql_text.splitlines():
        if line.startswith("--"):
            return line.lstrip("- ").strip()
    return ""


def to_markdown(columns, rows):
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    for row in rows[:PREVIEW_ROWS]:
        lines.append("| " + " | ".join("" if v is None else str(v) for v in row) + " |")
    if len(rows) > PREVIEW_ROWS:
        lines.append(f"\n_{len(rows) - PREVIEW_ROWS} more rows in the CSV._")
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--project", required=True, help="Your Google Cloud project ID (billing project)")
    parser.add_argument("--only", default="", help="Run only queries whose file name starts with this")
    parser.add_argument("--max-gb", type=float, default=5.0, help="Skip any query that would scan more than this")
    args = parser.parse_args()

    files = sorted(p for p in SQL_DIR.glob("*.sql") if p.name.startswith(args.only))
    if not files:
        raise SystemExit(f"No queries found matching '{args.only}'")
    RESULTS_DIR.mkdir(exist_ok=True)

    client = bigquery.Client(project=args.project)
    summary = ["# Results\n", "Generated by `scripts/run_analysis.py`.\n"]
    total_gb = 0.0

    for path in files:
        sql = path.read_text(encoding="utf-8")

        dry = client.query(sql, job_config=bigquery.QueryJobConfig(dry_run=True, use_query_cache=False))
        gb = dry.total_bytes_processed / 1e9
        if gb > args.max_gb:
            print(f"{path.stem:<36} SKIPPED: would scan {gb:.2f} GB (limit {args.max_gb} GB)")
            continue

        result = client.query(sql).result()
        columns = [field.name for field in result.schema]
        rows = [list(row.values()) for row in result]
        total_gb += gb

        with open(RESULTS_DIR / f"{path.stem}.csv", "w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(columns)
            writer.writerows(rows)

        summary += [f"## {title_of(sql)}\n", f"Query: `sql/{path.name}`\n", to_markdown(columns, rows), ""]
        print(f"{path.stem:<36} {len(rows):>5} rows   {gb:.2f} GB scanned")

    if not args.only:
        (RESULTS_DIR / "SUMMARY.md").write_text("\n".join(summary), encoding="utf-8")
    print(f"\nTotal scanned: {total_gb:.2f} GB (sandbox allows 1,000 GB/month free)")


if __name__ == "__main__":
    main()
